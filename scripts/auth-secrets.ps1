#Requires -Version 7.0
<#
.SYNOPSIS
Generate GLANCE_SECRET_KEY and GLANCE_PASSWORD_HASH for the Asgard deployment and
print them ready to paste into the Arcane project's Configuration tab.

.PARAMETER Write
Also write glance/asgard.env (git-ignored) for scripts/test-asgard.ps1, copying the
Steam and weather values from glance/.env if present.

.PARAMETER RotateKey
Generate only a new secret key. This is how to end every session: logging out and
changing the password do not revoke them.
#>
[CmdletBinding()]
param(
    [switch]$Write,
    [switch]$RotateKey
)

$ErrorActionPreference = 'Stop'

$repoRoot          = (Resolve-Path (Join-Path $PSScriptRoot '..')).Path
$glanceDir         = Join-Path $repoRoot 'glance'
$envOut            = Join-Path $glanceDir 'asgard.env'
$localEnv          = Join-Path $glanceDir '.env'
$minPasswordLength = 12

# Same Glance release as the image, so the hash format always matches.
$image = Get-Content (Join-Path $glanceDir 'dockerfile') |
    Select-String -Pattern '^FROM\s+(glanceapp/glance:\S+)' |
    Select-Object -First 1 |
    ForEach-Object { $_.Matches[0].Groups[1].Value }
if (-not $image) { throw "Could not find a glanceapp/glance FROM line in $glanceDir/dockerfile" }

Write-Host "Using $image"

$secret = (& docker run --rm --entrypoint /app/glance $image secret:make | Out-String).Trim()
if ($LASTEXITCODE -ne 0) { throw 'secret:make failed' }
$secretBytes = [Convert]::FromBase64String($secret).Length
if ($secretBytes -ne 64) { throw "secret:make returned $secretBytes bytes, expected 64" }

$hash = $null
if (-not $RotateKey) {
    $password  = Read-Host "Password for user 'piotr'" -AsSecureString | ConvertFrom-SecureString -AsPlainText
    $password2 = Read-Host 'Repeat password' -AsSecureString | ConvertFrom-SecureString -AsPlainText
    if ($password -cne $password2) { throw 'Passwords do not match' }
    if ($password.Length -lt $minPasswordLength) { throw "Password must be at least $minPasswordLength characters" }

    # Passed through the environment rather than as an argument, so it never
    # appears in the host's process list.
    $env:GLANCE_PW = $password
    try {
        $hash = (& docker run --rm -e GLANCE_PW --entrypoint sh $image -c '/app/glance password:hash "$GLANCE_PW"' | Out-String).Trim()
        if ($LASTEXITCODE -ne 0) { throw 'password:hash failed' }
    }
    finally {
        Remove-Item Env:GLANCE_PW -ErrorAction SilentlyContinue
        $password = $null; $password2 = $null
    }
    if (-not $hash.StartsWith('$2')) { throw 'password:hash did not return a bcrypt hash' }
}

Write-Host ''
Write-Host "Paste into the Arcane project's Configuration tab. Keep the single quotes:"
Write-Host 'the hash contains $ signs that Compose would otherwise interpolate.'
Write-Host ''
Write-Host "GLANCE_SECRET_KEY='$secret'"
if ($hash) { Write-Host "GLANCE_PASSWORD_HASH='$hash'" }
Write-Host ''
if ($RotateKey) { Write-Host 'Then Redeploy the project (not Restart). Every existing session ends.' }

if (-not $Write) { return }

# LF endings: scripts/test-asgard.sh sources this file, and a CR would end up
# inside every value.
function Save-EnvFile([string[]]$Lines) {
    [IO.File]::WriteAllText($envOut, (($Lines -join "`n") + "`n"))
}

if ($RotateKey) {
    if (-not (Test-Path $envOut)) { throw "$envOut does not exist; run without -RotateKey first" }
    $lines = @(Get-Content $envOut | Where-Object { $_ -notmatch '^GLANCE_SECRET_KEY=' })
    Save-EnvFile ($lines + "GLANCE_SECRET_KEY='$secret'")
    Write-Host "Updated GLANCE_SECRET_KEY in $envOut"
    return
}

function Get-LocalValue([string]$Name) {
    if (-not (Test-Path $localEnv)) { return '' }
    $line = Get-Content $localEnv | Where-Object { $_ -match "^$Name=" } | Select-Object -First 1
    if ($line) { return ($line -replace "^$Name=", '').Trim() }
    return ''
}

$weather = Get-LocalValue 'WEATHER_LOCATION'
if (-not $weather) { $weather = 'London' }

Save-EnvFile @(
    '# Generated by scripts/auth-secrets for scripts/test-asgard. Git-ignored.'
    "STEAM_API_KEY='$(Get-LocalValue 'STEAM_API_KEY')'"
    "STEAM_USER='$(Get-LocalValue 'STEAM_USER')'"
    "WEATHER_LOCATION='$weather'"
    "GLANCE_SECRET_KEY='$secret'"
    "GLANCE_PASSWORD_HASH='$hash'"
)
Write-Host "Wrote $envOut"
