#!/usr/bin/env bash
set -euo pipefail

# Git Bash rewrites container-side paths like /app/glance into Windows ones.
# Nothing here passes a host path to docker, so it is safe for the whole script.
export MSYS_NO_PATHCONV=1

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
REPO_ROOT="$(cd "$SCRIPT_DIR/.." && pwd)"
GLANCE_DIR="$REPO_ROOT/glance"
ENV_OUT="$GLANCE_DIR/asgard.env"
LOCAL_ENV="$GLANCE_DIR/.env"
MIN_PASSWORD_LENGTH=12

write=0
rotate_key=0

usage() {
  cat <<EOF
Usage: $(basename "$0") [--write] [--rotate-key]

Generate GLANCE_SECRET_KEY and GLANCE_PASSWORD_HASH for the Asgard deployment
and print them ready to paste into the Arcane project's Configuration tab.

Options:
  --write       Also write glance/asgard.env (git-ignored) for scripts/test-asgard.sh,
                copying the Steam and weather values from glance/.env if present
  --rotate-key  Generate only a new secret key. This is how to end every session:
                logging out and changing the password do not revoke them
  -h, --help    Show this message
EOF
}

while [[ $# -gt 0 ]]; do
  case "$1" in
    --write) write=1 ;;
    --rotate-key) rotate_key=1 ;;
    -h|--help) usage; exit 0 ;;
    *) echo "Unknown option: $1" >&2; usage >&2; exit 2 ;;
  esac
  shift
done

# Same Glance release as the image, so the hash format always matches.
image="$(tr -d '\r' < "$GLANCE_DIR/dockerfile" \
  | sed -n 's/^FROM[[:space:]]\{1,\}\(glanceapp\/glance:[^[:space:]]*\).*/\1/p' | head -n 1)"
if [[ -z "$image" ]]; then
  echo "Could not find a glanceapp/glance FROM line in $GLANCE_DIR/dockerfile" >&2
  exit 1
fi

echo "Using $image"

secret="$(docker run --rm --entrypoint /app/glance "$image" secret:make | tr -d '\r\n')"
secret_bytes="$(printf '%s' "$secret" | base64 -d 2>/dev/null | wc -c | tr -d ' ')"
if [[ "$secret_bytes" -ne 64 ]]; then
  echo "secret:make returned ${secret_bytes} bytes, expected 64" >&2
  exit 1
fi

hash=""
if [[ $rotate_key -eq 0 ]]; then
  read -r -s -p "Password for user 'piotr': " password; echo
  read -r -s -p "Repeat password: " password2; echo
  if [[ "$password" != "$password2" ]]; then
    echo "Passwords do not match" >&2
    exit 1
  fi
  if [[ ${#password} -lt $MIN_PASSWORD_LENGTH ]]; then
    echo "Password must be at least $MIN_PASSWORD_LENGTH characters" >&2
    exit 1
  fi

  # Passed through the environment rather than as an argument, so it never
  # appears in the host's process list.
  hash="$(GLANCE_PW="$password" docker run --rm -e GLANCE_PW --entrypoint sh "$image" \
    -c '/app/glance password:hash "$GLANCE_PW"' | tr -d '\r\n')"
  unset password password2
  if [[ "$hash" != \$2* ]]; then
    echo "password:hash did not return a bcrypt hash" >&2
    exit 1
  fi
fi

echo
echo "Paste into the Arcane project's Configuration tab. Keep the single quotes:"
echo "the hash contains \$ signs that Compose would otherwise interpolate."
echo
echo "GLANCE_SECRET_KEY='$secret'"
[[ -n "$hash" ]] && echo "GLANCE_PASSWORD_HASH='$hash'"
echo
if [[ $rotate_key -eq 1 ]]; then
  echo "Then Redeploy the project (not Restart). Every existing session ends."
fi

if [[ $write -eq 0 ]]; then
  exit 0
fi

if [[ $rotate_key -eq 1 ]]; then
  if [[ ! -f "$ENV_OUT" ]]; then
    echo "$ENV_OUT does not exist; run without --rotate-key first" >&2
    exit 1
  fi
  tmp="$(mktemp)"
  grep -v '^GLANCE_SECRET_KEY=' "$ENV_OUT" > "$tmp" || true
  echo "GLANCE_SECRET_KEY='$secret'" >> "$tmp"
  mv "$tmp" "$ENV_OUT"
  echo "Updated GLANCE_SECRET_KEY in $ENV_OUT"
  exit 0
fi

local_value() {
  [[ -f "$LOCAL_ENV" ]] || return 0
  tr -d '\r' < "$LOCAL_ENV" | sed -n "s/^$1=//p" | head -n 1
}

{
  echo "# Generated by scripts/auth-secrets.sh for scripts/test-asgard.sh. Git-ignored."
  echo "STEAM_API_KEY='$(local_value STEAM_API_KEY)'"
  echo "STEAM_USER='$(local_value STEAM_USER)'"
  weather="$(local_value WEATHER_LOCATION)"
  echo "WEATHER_LOCATION='${weather:-London}'"
  echo "GLANCE_SECRET_KEY='$secret'"
  echo "GLANCE_PASSWORD_HASH='$hash'"
} > "$ENV_OUT"
chmod 600 "$ENV_OUT" 2>/dev/null || true
echo "Wrote $ENV_OUT"
